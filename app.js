function toggleCardLoupe(event, productId) {
  event.stopPropagation();
  if (cardLoupeActive.has(productId)) {
    cardLoupeActive.delete(productId);
  } else {
    cardLoupeActive.add(productId);
  }
  renderProducts();
}

function attachCard3DAndLoupeListeners() {
  document.querySelectorAll('.product-img-wrapper').forEach((mediaBox) => {
    const pid = mediaBox.dataset.pid;
    const imgUrl = mediaBox.dataset.img;
    const stage = mediaBox.querySelector('.product-3d-stage');
    const glare = mediaBox.querySelector('.product-glare');
    const loupe = mediaBox.querySelector('.optical-loupe');
    let isDraggingCard = false;
    let startX = 0;
    let spinOffset = 0;

    loupe.style.backgroundImage = `url('${imgUrl}')`;

    mediaBox.addEventListener('mousedown', (e) => {
      if (e.target.closest('.card-loupe-toggle')) return;
      isDraggingCard = true;
      startX = e.clientX;
    });

    window.addEventListener('mouseup', () => {
      if (isDraggingCard) {
        isDraggingCard = false;
      }
    });

    mediaBox.addEventListener('mousemove', (e) => {
      const rect = mediaBox.getBoundingClientRect();
      const x = e.clientX - rect.left;
      const y = e.clientY - rect.top;
      const pctX = x / rect.width;
      const pctY = y / rect.height;

      // 1. If card optical magnifier is enabled, show crystal loupe lens
      if (cardLoupeActive.has(pid)) {
        stage.style.transform = 'rotateX(0deg) rotateY(0deg)';
        loupe.classList.add('visible');
        loupe.style.left = `${x}px`;
        loupe.style.top = `${y}px`;
        const zoom = 2.8;
        loupe.style.backgroundSize = `${rect.width * zoom}px ${rect.height * zoom}px`;
        const bgX = Math.max(0, Math.min(100, pctX * 100));
        const bgY = Math.max(0, Math.min(100, pctY * 100));
        loupe.style.backgroundPosition = `${bgX}% ${bgY}%`;
        return;
      }

      loupe.classList.remove('visible');

      // 2. Real-time 3D cursor tilt + horizontal drag spin
      if (isDraggingCard) {
        spinOffset = (e.clientX - startX) * 0.9;
      }
      const rotY = (pctX - 0.5) * 36 + spinOffset;
      const rotX = (0.5 - pctY) * 28;
      stage.style.transform = `rotateX(${rotX.toFixed(1)}deg) rotateY(${rotY.toFixed(1)}deg) scale3d(1.04, 1.04, 1.04)`;

      if (glare) {
        glare.style.background = `radial-gradient(circle at ${(pctX * 100).toFixed(0)}% ${(pctY * 100).toFixed(0)}%, rgba(255,255,255,0.65) 0%, transparent 62%)`;
      }
    });

    mediaBox.addEventListener('mouseleave', () => {
      isDraggingCard = false;
      spinOffset = 0;
      stage.style.transform = 'rotateX(0deg) rotateY(0deg) scale3d(1,1,1)';
      loupe.classList.remove('visible');
    });

    mediaBox.addEventListener('click', (e) => {
      if (e.target.closest('.card-loupe-toggle')) return;
      openProductModal(pid);
    });
  });
}

function filterByCategory(category, scrollToCatalog = false) {
  activeCategory = category;
  document.querySelectorAll('.cat-tab').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.cat === category);
  });
  renderProducts();
  if (scrollToCatalog) {
    const section = document.getElementById('katalog');
    if (section) section.scrollIntoView({ behavior: 'smooth' });
  }
}

function resetCatalogFilter() {
  searchQuery = '';
  const searchInput = document.getElementById('catalogSearchInput');
  if (searchInput) searchInput.value = '';
  filterByCategory('all');
}

