function toggleStudioAutoSpin() {
  const spinBtn = document.getElementById('studioAutoSpinBtn');
  if (studioAutoSpinTimer) {
    stopStudioAutoSpin();
    return;
  }
  studioMode = '3d';
  const loupe = document.getElementById('studioLoupe');
  if (loupe) loupe.classList.remove('visible');
  if (spinBtn) spinBtn.classList.add('active');

  studioAutoSpinTimer = setInterval(() => {
    studioRotY = ((studioRotY + 190) % 360) - 180;
    const obj = document.getElementById('studio3DObject');
    const slider = document.getElementById('studioAngleSlider');
    const valEl = document.getElementById('studioAngleVal');
    if (obj) {
      obj.style.transform = `rotateX(${studioRotX.toFixed(1)}deg) rotateY(${studioRotY.toFixed(1)}deg)`;
    }
    if (slider) slider.value = Math.round(studioRotY);
    if (valEl) valEl.textContent = `${Math.round(studioRotY)}°`;
  }, 35);
}

function bindStudioStageEvents() {
  const wrap = document.getElementById('studioStageWrap');
  const obj = document.getElementById('studio3DObject');
  const loupe = document.getElementById('studioLoupe');
  const slider = document.getElementById('studioAngleSlider');
  const valEl = document.getElementById('studioAngleVal');
  if (!wrap || !obj || !loupe) return;

  loupe.style.backgroundImage = `url('${currentStudioImage}')`;

  if (slider) {
    slider.addEventListener('input', (e) => {
      stopStudioAutoSpin();
      studioRotY = parseFloat(e.target.value);
      obj.style.transform = `rotateX(${studioRotX.toFixed(1)}deg) rotateY(${studioRotY.toFixed(1)}deg)`;
      if (valEl) valEl.textContent = `${Math.round(studioRotY)}°`;
    });
  }

  wrap.addEventListener('wheel', (e) => {
    e.preventDefault();
    const delta = e.deltaY < 0 ? 0.5 : -0.5;
    studioZoom = Math.max(2, Math.min(6, +(studioZoom + delta).toFixed(1)));
    loupe.setAttribute('data-zoom', `${studioZoom}x HD`);
    const rect = wrap.getBoundingClientRect();
    loupe.style.backgroundSize = `${rect.width * studioZoom}px ${rect.height * studioZoom}px`;
  }, { passive: false });

  wrap.addEventListener('mousedown', (e) => {
    if (studioMode !== '3d') return;
    stopStudioAutoSpin();
    studioDragging = true;
    studioDragStartX = e.clientX - studioRotY * 2.2;
    studioDragStartY = e.clientY + studioRotX * 2.5;
  });

  window.addEventListener('mouseup', () => {
    studioDragging = false;
  });

  wrap.addEventListener('mousemove', (e) => {
    const rect = wrap.getBoundingClientRect();
    const x = e.clientX - rect.left;
    const y = e.clientY - rect.top;
    const pctX = Math.max(0, Math.min(1, x / rect.width));
    const pctY = Math.max(0, Math.min(1, y / rect.height));

    if (studioMode === 'loupe') {
      loupe.classList.add('visible');
      loupe.style.left = `${x}px`;
      loupe.style.top = `${y}px`;
      loupe.style.backgroundSize = `${rect.width * studioZoom}px ${rect.height * studioZoom}px`;
      loupe.style.backgroundPosition = `${(pctX * 100).toFixed(2)}% ${(pctY * 100).toFixed(2)}%`;
      // Subtle 3D parallax even in loupe mode
      const subtleY = (pctX - 0.5) * 10;
      const subtleX = (0.5 - pctY) * 8;
      obj.style.transform = `rotateX(${subtleX.toFixed(1)}deg) rotateY(${subtleY.toFixed(1)}deg)`;
    } else {
      loupe.classList.remove('visible');
      if (studioDragging) {
        studioRotY = Math.max(-180, Math.min(180, (e.clientX - studioDragStartX) / 2.2));
        studioRotX = Math.max(-42, Math.min(42, (studioDragStartY - e.clientY) / 2.5));
      } else if (!studioAutoSpinTimer) {
        studioRotY = (pctX - 0.5) * 70;
        studioRotX = (0.5 - pctY) * 42;
      }
      obj.style.transform = `rotateX(${studioRotX.toFixed(1)}deg) rotateY(${studioRotY.toFixed(1)}deg) scale3d(1.04, 1.04, 1.04)`;
      if (slider) slider.value = Math.round(studioRotY);
      if (valEl) valEl.textContent = `${Math.round(studioRotY)}°`;
    }
  });

  wrap.addEventListener('mouseleave', () => {
    loupe.classList.remove('visible');
    if (studioMode === 'loupe') {
      obj.style.transform = 'rotateX(0deg) rotateY(0deg)';
    }
  });
}

